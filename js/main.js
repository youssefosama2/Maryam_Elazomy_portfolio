(function () {
  var form = document.getElementById("contactForm");
  var status = document.getElementById("contactStatus");

  if (!form || !status) return;
  

  var SERVICE_ID = "service_pbnx118";
  var TEMPLATE_ID = "template_ac4wpoj";
  var PUBLIC_KEY = "lDLMDrd9R8yz2ps7X";

  if (!window.emailjs) {
    status.textContent = "Contact service is unavailable. Please try again later.";
    status.className = "contact-status error";
    return;
  }

  emailjs.init({
    publicKey: PUBLIC_KEY
  });

  var submitButton = form.querySelector('[type="submit"]');
  var submitText = submitButton
    ? submitButton.querySelector(".submit-text")
    : null;

  var originalText = submitText
    ? submitText.textContent
    : "Send Message";

  function validateField(field) {
    var input = field.querySelector("input, textarea");
    if (!input) return true;

    var valid = input.checkValidity() && input.value.trim() !== "";

    if (input.name === "from_name" && input.value.trim().length < 2) {
      valid = false;
    }

    if (input.name === "message" && input.value.trim().length < 10) {
      valid = false;
    }

    field.classList.toggle("invalid", !valid);
    return valid;
  }

  var fields = Array.from(form.querySelectorAll(".form-field"));

  fields.forEach(function (field) {
    var input = field.querySelector("input, textarea");
    if (!input) return;

    input.addEventListener("input", function () {
      if (field.classList.contains("invalid")) {
        validateField(field);
      }
    });

    input.addEventListener("blur", function () {
      if (input.value.trim() !== "") {
        validateField(field);
      }
    });
  });

  form.addEventListener("submit", async function (event) {
    event.preventDefault();

    var valid = fields.reduce(function (result, field) {
      return validateField(field) && result;
    }, true);

    if (!valid) {
      status.textContent = "Please check the highlighted fields and try again.";
      status.className = "contact-status error";

      var firstInvalid = form.querySelector(".form-field.invalid input, .form-field.invalid textarea");
      if (firstInvalid) firstInvalid.focus();

      return;
    }

    if (submitButton) submitButton.disabled = true;
    if (submitText) submitText.textContent = "Sending...";

    status.textContent = "";
    status.className = "contact-status";

    try {
      await emailjs.sendForm(SERVICE_ID, TEMPLATE_ID, form);

      status.textContent = "Your message has been sent successfully. Thank you!";
      status.className = "contact-status success";

      form.reset();

      fields.forEach(function (field) {
        field.classList.remove("invalid");
      });
    } catch (error) {
      console.error("EmailJS error:", error);

      status.textContent = "Something went wrong. Please try again later.";
      status.className = "contact-status error";
    } finally {
      if (submitButton) submitButton.disabled = false;
      if (submitText) submitText.textContent = originalText;
    }
  });
})();

